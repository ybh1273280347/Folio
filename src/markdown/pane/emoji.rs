/// Match a colon token at a word boundary, keeping its UTF-8 byte length for
/// capture_suffix. Reject ASCII word prefixes so URLs and times do not open it.
pub(super) fn query(prefix: &str) -> Option<(usize, String)> {
    let start = prefix.rfind(':')?;
    if let Some(previous) = prefix[..start].chars().next_back()
        && (previous.is_ascii_alphanumeric() || matches!(previous, '_' | '/' | ':' | '\\'))
    {
        return None;
    }
    let query = &prefix[start + 1..];
    if query.chars().count() > 32
        || query.chars().any(|ch| !(ch.is_alphanumeric() || matches!(ch, '_' | '-' | '+')))
    {
        return None;
    }
    Some((query.len() + 1, query.to_lowercase()))
}
